def normalize_args(args):
    if hasattr(args, 'resume_adapter') and not hasattr(args, 'init_adapter'):
        args.init_adapter = args.resume_adapter
    if not hasattr(args, 'save_steps'):
        args.save_steps = getattr(args, 'save_every', 2000)
    # Fill missing fields for the legacy Python wrappers, using the same parser
    # defaults as the public CLI instead of maintaining another recipe.
    parser_defaults = _parser().parse_args([getattr(args, "command", "train"),
                                           "--output", args.output])
    for key, value in vars(parser_defaults).items():
        if not hasattr(args, key):
            setattr(args, key, value)
    binding = BindingConfig(args.binding, args.binding_beta, args.binding_eps, args.binding_rank)
    if args.stage == "stage1" and binding.mode != "none":
        raise ValueError("--binding is a Stage 2 (DiT) option")
    if getattr(args, 'init_adapter', None):
        config = json.loads((Path(args.init_adapter) / 'adapter.json').read_text())
        if config['stage'] != args.stage:
            raise ValueError('--init-adapter belongs to another stage')
        for key in ('rank', 'dropout'):
            if getattr(args, key, None) is not None and getattr(args, key) != config[key]:
                raise ValueError(f'Explicit --{key} conflicts with warm-start adapter')
            setattr(args, key, config[key])
        if adapter_binding(config) != binding:
            raise ValueError('--binding conflicts with the warm-start adapter')
    args.binding_config = binding.as_dict()
    defaults = {
        "stage1": {"accumulation": 8, "rank": 64, "dropout": 0.05, "lr": 4e-5, "weight_decay": 0.05},
        "stage2": {"accumulation": 4, "rank": 32, "dropout": 0.0, "lr": 1e-4, "weight_decay": 0.01},
    }[args.stage]
    if args.lr_schedule is None:
        args.lr_schedule = "cosine" if args.stage == "stage1" else "constant"
    if args.type_weights is None:
        # Stage 1 makes several passes: no type is repeated more than its rows
        # allow. Stage 2 makes under one pass: add/remove/replace/attribute
        # keep the v1 balance and every other type stays at its natural share.
        args.type_weights = "natural" if args.stage == "stage1" else "main4"
    if args.lr_schedule not in {"constant", "cosine"}:
        raise ValueError("lr-schedule must be constant or cosine")
    if args.warmup_steps is not None and args.warmup_ratio is not None:
        raise ValueError("Choose either warmup-steps or warmup-ratio")
    if args.warmup_ratio is None and args.warmup_steps is None:
        args.warmup_ratio = 0.04 if args.stage == "stage1" else 0.025
    if args.warmup_ratio is not None and (not math.isfinite(args.warmup_ratio) or not 0 <= args.warmup_ratio <= 1):
        raise ValueError("warmup-ratio must be finite and lie in [0, 1]")
    if args.warmup_steps is not None and args.warmup_steps < 0:
        raise ValueError("warmup-steps must be nonnegative")
    for key, value in defaults.items():
        if getattr(args, key) is None:
            setattr(args, key, value)
    if args.accumulation < 1 or (args.steps is not None and args.steps < 1):
        raise ValueError("accumulation/steps must be positive")
    if not math.isfinite(args.ntp_weight) or args.ntp_weight <= 0:
        raise ValueError("ntp_weight must be finite and positive")
    return args


def main(argv=None):
    args = normalize_args(_parser().parse_args(argv))
    if args.command == "cache":
        if not args.metadata:
            raise SystemExit("cache requires --metadata")
        run_cache(args)
    else:
        if args.stage == "stage1" and not args.metadata:
            raise SystemExit("stage1 train requires --metadata")
        if args.stage == "stage2" and bool(args.cache) == bool(args.metadata):
            raise SystemExit("stage2 train needs exactly one of --cache or --metadata (on-the-fly conditioning)")
        try:
            validate_training_length_and_saves(args)
        except ValueError as exc:
            raise SystemExit(str(exc)) from exc
        run_train(args)


if __name__ == "__main__":
    main()
