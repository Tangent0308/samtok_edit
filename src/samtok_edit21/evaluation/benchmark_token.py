"""Benchmark v2 (2.6.0) editor adapter: every unit's region as a SAMTok mask token in its instruction.

The benchmark's own runner calls ``edit`` (``samtok-benchmark-v2 run-editor --adapter
samtok_edit21.evaluation.benchmark_token:edit``) on public benchmark jobs.  Each unit's region becomes one SAMTok
token, built only from the locator the job supplies:
* ``native_regions_v2`` jobs (the same per-unit point / box / mask as the official visual-locator setting, given as
  coordinates and files): a mask is encoded directly; a point or a box goes through SAM2.1 (the codec's original
  weights, best of the multi-mask candidates by predicted IoU), the way an interactive user would click or drag;
* ``mask_full`` jobs (one grayscale label map with every unit's mask, U1..U5 = gray 51..255): the unit's mask from it.
Units without a locator (ref + none) stay text only.  The unit's instruction text stays as given and the token is
placed after its selector (protocol 2.0 rendering, checked against the given text).  Generation is
token-only (no pixel mask, no attention bias, no blending; only the ``teacher`` test below blends), CFG 1, about 1 MP
on a 32 px grid, exported at the source size like the official Qwen-Image-2.1 adapter.

    python -m samtok_edit21.evaluation.benchmark_token --jobs <jobs.jsonl> --output <run dir> \\
        --config <config.json> --benchmark <benchmark clone> --gpus 0,1,2,3,4,5,6,7

Config keys:
* ``adapter``: adapter directory, or null for the stock DiT;
* ``mode``: "joint" (one generation, numbered U1.. lines as in the round-2 multi-edit rows) or "sequential" (one
  unit per generation, in unit order, each on the previous output);
* ``describe``: no-ref units first get a short name generated by the SAMTok text encoder from the token itself and
  are then read as name + token (the region never leaves the token);
* ``ground``: units without a locator (ref + none) first get a token from the raw SAMTok text encoder, which segments
  the unit's selector phrase (pass 1); the unit then reads as ref + token, and stays text only if no valid token comes;
* ``token_guidance`` (default 1, off): a second prediction per step from the same prompt with every region token
  removed, and the difference amplified (CFG with that token-free prompt as the negative branch); only prompts that
  carry a token, the rest run as before;
* ``teacher`` (teacher-capability test for on-policy self-distillation, analysis/opsd_teacher_20261025; reads the
  ground truth, so never a benchmark submission): ``gt_masks`` makes every unit's token from its ground-truth mask
  (manifest ``target.mask``) instead of the job's locator; ``ref`` reads every unit as ref + token, the blind ones
  too; ``blend`` = {"dilate", "feather", "add_expand"} keeps the source outside the allowed region (latent blending):
  the union of the units' ground-truth masks, an add unit's box also grown by ``add_expand`` of its size on every
  side, then dilated and feathered by the given numbers of tokens;
* ``steps``, ``qwen``, ``samtok``;
* ``manifest``: the release ``cases.jsonl``; only the instruction specs are read, to place the token and (with
  ``ground``) to take the selector phrase, which is part of the given instruction (with ``teacher`` also the
  ground-truth masks);
* ``log``: directory for one JSON per job with the prompts, names and token round trips.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image

GRAY = {"U1": 51, "U2": 102, "U3": 153, "U4": 204, "U5": 255}
DESCRIBE = "What object is {span}? Answer in at most five words."
GROUND = "Can you segment {ref}?"
TOKEN_SPAN = re.compile(r"\s*<\|mt_start\|>(?:<\|mt_\d+\|>)*<\|mt_end\|>")
HEAD_END = re.compile(r"\s(?:with|featuring|that|which|having|showing|is|are|on|in)\s|[.;:(]")
_STATE = {}


def _models(config):
    key = (config.get("adapter"), config["qwen"], config["samtok"])
    if _STATE.get("key") != key:
        from samtok_edit21.models.codec import load_codec
        from samtok_edit21.models.pipeline import load_pipeline
        from samtok_edit21.models.adapters import load_grounding_adapter

        pipe = load_pipeline(config["qwen"], config["samtok"], device="cuda")
        codec = load_codec(config["samtok"], "cuda")
        if config.get("adapter"):
            load_grounding_adapter(pipe, codec, config["adapter"])
        pipe.eval()
        _STATE.update(key=key, pipe=pipe, codec=codec)
    return _STATE["pipe"], _STATE["codec"]


def _specs(manifest):
    if _STATE.get("manifest") != manifest:
        cases = (json.loads(line) for line in open(manifest))
        _STATE["specs"] = {c["id"]: {u["id"]: u["instruction_spec"] for u in c["units"]} for c in cases}
        _STATE["manifest"] = manifest
    return _STATE["specs"]


def _targets(manifest):
    """Ground-truth targets per case and unit (teacher test only): operation, mask path (absolute) and box."""
    if _STATE.get("targets_manifest") != manifest:
        root = Path(manifest).resolve().parents[1]
        _STATE["targets"] = {c["id"]: {u["id"]: {"operation": u["operation"], "mask": str(root / u["target"]["mask"]),
                                                 "box": u["target"]["box"]} for u in c["units"]}
                             for c in map(json.loads, open(manifest))}
        _STATE["targets_manifest"] = manifest
    return _STATE["targets"]


def ground_truth_mask(target, size):
    """A unit's ground-truth mask at the source size ``(width, height)``."""
    with Image.open(target["mask"]) as im:
        mask = im.convert("L")
        if mask.size != size:
            mask = mask.resize(size, Image.NEAREST)
        return np.asarray(mask) > 0


def allowed_region(targets, masks, size, add_expand=0.5):
    """Where the teacher may change the image: the union of the units' masks; an add unit may also reach its box grown
    by ``add_expand`` of the box size on every side (a new object can stand out of its attachment site)."""
    width, height = size
    region = np.zeros((height, width), bool)
    for uid, target in targets.items():
        region |= masks[uid]
        if target["operation"] == "add" and add_expand:
            x1, y1, x2, y2 = target["box"]
            dx, dy = (x2 - x1) * add_expand, (y2 - y1) * add_expand
            region[max(0, int(y1 - dy)):min(height, int(np.ceil(y2 + dy))),
                   max(0, int(x1 - dx)):min(width, int(np.ceil(x2 + dx)))] = True
    return region


def unit_masks(job, codec=None, source=None):
    """Each unit's region from the locator the job supplies (empty for text-only units); also the region source."""
    if job["protocol"] == "native_regions_v2":
        from samtok_edit21.regions.selection import segment

        masks, how = {}, {}
        for u in job["units"]:
            region = u.get("region") or {}
            if "mask" in region:
                masks[u["id"]], how[u["id"]] = np.asarray(Image.open(region["mask"]).convert("L")) > 0, "mask"
            elif "box" in region or "point" in region:
                if "box" in region:
                    candidates, scores = segment(codec, source, box=region["box"])
                else:
                    candidates, scores = segment(codec, source, points=[(*region["point"], 1)])
                best = int(np.argmax(scores))
                masks[u["id"]], how[u["id"]] = candidates[best], f"sam2_{'box' if 'box' in region else 'point'}"
            else:
                masks[u["id"]], how[u["id"]] = np.zeros((source.height, source.width), bool), "none"
        return masks, how
    label = np.asarray(Image.open(job["images"][1]).convert("L"))
    return {u["id"]: label == GRAY[u["id"]] for u in job["units"]}, {u["id"]: "label_map" for u in job["units"]}


def clean_phrase(raw):
    """The head noun phrase of the encoder's answer: "A tall, wooden pole with a crossbar." -> "the tall wooden pole"."""
    phrase = raw.strip().split("\n")[0].strip().strip("\"'")
    phrase = HEAD_END.split(" " + phrase, maxsplit=1)[0].replace(",", " ")
    words = re.sub(r"^(a|an|the)\s+", "", " ".join(phrase.split()), flags=re.IGNORECASE).split()[:6]
    return "the " + " ".join(words).lower() if words else ""


def describe(pipe, source, span, max_new_tokens=24):
    """A short name for the token's region, generated by the raw SAMTok text encoder from the image and the token."""
    import torch

    from samtok_edit21.data.protocol import EMPTY_THINK
    from samtok_edit21.models.pipeline import QwenImage21Unit_PromptEmbedder, te_adapters

    content = [{"type": "image"}, {"type": "text", "text": DESCRIBE.format(span=span)}]
    text = pipe.processor.apply_chat_template([{"role": "user", "content": content}], tokenize=False,
                                              add_generation_prompt=True) + EMPTY_THINK
    image = QwenImage21Unit_PromptEmbedder.composite_over_white(source.convert("RGBA"))
    inputs = pipe.processor(text=[text], images=[image], return_tensors="pt", padding=True).to(pipe.device)
    tokenizer = pipe.processor.tokenizer
    with te_adapters(pipe, False), torch.no_grad():
        ids = pipe.text_encoder.generate(**inputs, max_new_tokens=max_new_tokens, do_sample=False, use_cache=True,
                                         eos_token_id=tokenizer.convert_tokens_to_ids("<|im_end|>"),
                                         pad_token_id=tokenizer.pad_token_id)
    return tokenizer.decode(ids[0, inputs.input_ids.shape[1]:], skip_special_tokens=True)


def ground(pipe, samtok, source, ref, max_new_tokens=64):
    """Pass 1 for a unit without a locator: the first region token the raw SAMTok text encoder generates when asked to
    segment ``ref`` (its own processor and chat format, as in the model card), or "" when it gives no valid token."""
    import torch
    from transformers import AutoProcessor

    from samtok_edit21.data.protocol import spans_in
    from samtok_edit21.models.pipeline import te_adapters

    if _STATE.get("ground_processor_dir") != samtok:
        _STATE.update(ground_processor=AutoProcessor.from_pretrained(samtok, local_files_only=True), ground_processor_dir=samtok)
    processor = _STATE["ground_processor"]
    messages = [{"role": "user", "content": [{"type": "image", "image": source.convert("RGB")},
                                             {"type": "text", "text": GROUND.format(ref=ref)}]}]
    inputs = processor.apply_chat_template(messages, tokenize=True, add_generation_prompt=True, return_dict=True,
                                           return_tensors="pt").to(pipe.device)
    with te_adapters(pipe, False), torch.no_grad():
        ids = pipe.text_encoder.generate(**inputs, max_new_tokens=max_new_tokens, do_sample=False)
    text = processor.batch_decode(ids[:, inputs["input_ids"].shape[1]:], skip_special_tokens=False)[0]
    try:
        spans = spans_in(text)
    except ValueError:
        return ""
    return spans[0] if spans else ""


def unit_sentence(spec, unit, span, name=None):
    """The given instruction with the token after its selector; ``name`` replaces the blind selector."""
    from samtok_edit21.preparation import instruction_protocol_v2 as p2

    if p2.render(spec, unit["has_ref"]) != unit["instruction"]:
        raise ValueError(f"{unit['id']}: the protocol rendering does not reproduce the given instruction")
    if not span:
        return unit["instruction"]
    if name and not unit["has_ref"]:
        return unit["instruction"].replace("the selected region", f"{name} {span}", 1)
    return p2.render(spec, unit["has_ref"], selector_token=span)


def strip_tokens(prompt):
    """The prompt with every region token removed: the negative branch of token guidance."""
    return re.sub(r"[ \t]+([.,;:])", r"\1", TOKEN_SPAN.sub("", prompt))


def generate_any(pipe, codec, prompt, image, *, steps, seed, guidance=1.0, blend=None):
    """Token-only generation; a prompt without any region token (ref + none units only) runs as plain text.  With
    ``guidance`` > 1 a prompt with tokens is also predicted without them, and the difference is amplified.
    ``blend`` (teacher test): {"region": pixel mask, "dilate", "feather"} keeps the source outside the region."""
    from samtok_edit21.evaluation.generation import canvas, export, generate
    from samtok_edit21.models.pipeline import edit as pipeline_edit

    blending = {} if blend is None else {"blend_region": blend["region"], "blend_dilate": blend["dilate"],
                                         "blend_feather": blend["feather"]}
    if "<|mt_start|>" in prompt:
        if guidance != 1.0:
            return generate(pipe, codec, prompt, image, steps=steps, seed=seed, cfg_scale=guidance,
                            negative_prompt=strip_tokens(prompt), **blending)[0]
        return generate(pipe, codec, prompt, image, steps=steps, seed=seed, **blending)[0]
    height, width = canvas(image)
    output, _ = pipeline_edit(pipe, prompt, [image.convert("RGBA")], mode="direct", height=height, width=width,
                              num_inference_steps=steps, cfg_scale=1.0, seed=seed, use_kv_cache=True, pass2_te="raw",
                              **blending)
    return export(output, image.size)


def edit(*, job, seed, config):
    from samtok_edit21.preparation import instruction_protocol_v2 as p2
    from samtok_edit21.preparation.round2_data import multi_edit_prompt

    pipe, codec = _models(config)
    specs = _specs(config["manifest"])[job["case_id"]]
    image = Image.open(job["images"][0]).convert("RGB")
    teacher = config.get("teacher") or {}
    if teacher.get("gt_masks"):
        targets = {u["id"]: _targets(config["manifest"])[job["case_id"]][u["id"]] for u in job["units"]}
        masks = {uid: ground_truth_mask(t, image.size) for uid, t in targets.items()}
        how = {uid: "gt_mask" for uid in masks}
    else:
        masks, how = unit_masks(job, codec, image)
    guidance = float(config.get("token_guidance", 1.0))
    log = {"job_id": job["job_id"], "units": [], "token_guidance": guidance, "teacher": teacher or None}
    blend = None
    if teacher.get("blend"):
        if not teacher.get("gt_masks") or config["mode"] != "joint":
            raise ValueError("teacher blending needs gt_masks and the joint mode")
        region = allowed_region(targets, masks, image.size, teacher["blend"].get("add_expand", 0.5))
        blend = {"region": region, "dilate": teacher["blend"].get("dilate", 2), "feather": teacher["blend"].get("feather", 1.0)}
        log["allowed_area"] = float(region.mean())

    def token(current, uid):
        mask = masks[uid]
        if not mask.any():
            span = ground(pipe, config["samtok"], current, specs[uid]["ref"]) if config.get("ground") else ""
            if span:
                masks[uid], how[uid] = codec.decode_strict(current.convert("RGBA"), span)[0] > 0, "te_ground"
            return span, None
        span = codec.encode(current.convert("RGBA"), [mask])[0][0]
        decoded = codec.decode_strict(current.convert("RGBA"), span)[0] > 0
        return span, float((decoded & mask).sum() / max((decoded | mask).sum(), 1))

    def sentence(current, unit):
        span, roundtrip = token(current, unit["id"])
        name = None
        if config.get("describe") and span and not unit["has_ref"]:
            raw = describe(pipe, current, span)
            name = clean_phrase(raw) or None
        text = unit_sentence(specs[unit["id"]], unit, span, name)
        if teacher.get("ref"):              # teacher test: every unit names its object, the blind ones too
            text = p2.render(specs[unit["id"]], True, selector_token=span) if span else p2.render(specs[unit["id"]], True)
        log["units"].append({"id": unit["id"], "region": how[unit["id"]], "area": float(masks[unit["id"]].mean()), "roundtrip": roundtrip,
                             "name": name, "sentence": text.replace(span, "<M>") if span else text})
        return text

    if config["mode"] == "joint":
        prompt = multi_edit_prompt([sentence(image, u) for u in job["units"]])
        image = generate_any(pipe, codec, prompt, image, steps=config["steps"], seed=seed, guidance=guidance, blend=blend)
    elif config["mode"] == "sequential":
        for unit in job["units"]:
            image = generate_any(pipe, codec, sentence(image, unit), image, steps=config["steps"], seed=seed,
                                 guidance=guidance)
    else:
        raise ValueError(f"unknown mode {config['mode']}")
    if config.get("log"):
        Path(config["log"]).mkdir(parents=True, exist_ok=True)
        (Path(config["log"]) / f"{job['job_id']}.json").write_text(json.dumps(log, ensure_ascii=False, indent=1))
    return image


def main(argv=None):
    p = argparse.ArgumentParser(description="Run the token adapter over benchmark jobs on several GPUs and merge the registries.")
    p.add_argument("--jobs", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--config", type=Path, required=True)
    p.add_argument("--benchmark", type=Path, required=True, help="benchmark repository checkout (v2branch)")
    p.add_argument("--gpus", default="0,1,2,3,4,5,6,7")
    p.add_argument("--method", default="samtok_token")
    a = p.parse_args(argv)
    repo = Path(__file__).resolve().parents[3]
    jobs = [json.loads(line) for line in open(a.jobs) if line.strip()]
    config = json.loads(a.config.read_text())
    a.output.mkdir(parents=True, exist_ok=True)
    config_path = a.output / "config.json"
    if config_path.exists() and json.loads(config_path.read_text()) != config:
        raise SystemExit(f"{config_path} differs from the requested config; use a new output directory")
    config_path.write_text(json.dumps(config, indent=1))
    env = {**os.environ, "PYTHONDONTWRITEBYTECODE": "1",
           "PYTHONPATH": os.pathsep.join(str(x) for x in (a.benchmark, repo / "src", repo / "third_party/diffsynth", repo / "third_party"))}
    procs = []
    for rank, gpu in enumerate(g for g in a.gpus.split(",") if g.strip()):
        shard = jobs[rank::len(a.gpus.split(","))]
        if not shard:
            continue
        shard_dir = a.output / "shards" / f"shard{rank:02d}"
        shard_dir.mkdir(parents=True, exist_ok=True)
        shard_jobs = shard_dir / "jobs.jsonl"
        if not shard_jobs.exists():
            shard_jobs.write_text("".join(json.dumps(j, ensure_ascii=False) + "\n" for j in shard))
        command = [sys.executable, "-m", "samtok_benchmark.v2.cli", "run-editor", "--inputs", str(shard_jobs),
                   "--output", str(shard_dir), "--adapter", "samtok_edit21.evaluation.benchmark_token:edit",
                   "--method", a.method, "--seed", "0", "--config", str(config_path)]
        log = (shard_dir / "run.log").open("a")
        procs.append((rank, subprocess.Popen(command, env={**env, "CUDA_VISIBLE_DEVICES": gpu.strip()},
                                             stdout=log, stderr=subprocess.STDOUT)))
    failed = [rank for rank, proc in procs if proc.wait() != 0]
    rows = sorted((json.loads(line) for shard in sorted((a.output / "shards").glob("shard*/outputs.jsonl"))
                   for line in open(shard) if line.strip()), key=lambda r: r["job_id"])
    (a.output / "outputs.jsonl").write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))
    print(json.dumps({"outputs": len(rows), "ok": sum(r["status"] == "ok" for r in rows), "failed_shards": failed}))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
